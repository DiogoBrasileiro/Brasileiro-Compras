-- 9. CONFIGURAR ARMAZENAMENTO DE ARQUIVOS (STORAGE)
INSERT INTO storage.buckets (id, name, public) VALUES ('budgets', 'budgets', true) ON CONFLICT (id) DO NOTHING;
DROP POLICY IF EXISTS "Allow All Storage" ON storage.objects;
CREATE POLICY "Allow All Storage" ON storage.objects FOR ALL USING (bucket_id = 'budgets') WITH CHECK (bucket_id = 'budgets');
